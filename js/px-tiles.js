const pxT=(rows,o)=>Object.assign({w:rows[0].length,h:rows.length,ax:0,ay:0,halo:false,outline:false,frames:{idle:[rows]}},o||{});   // Kachel/Muster
const pxP=(rows,o)=>Object.assign({w:rows[0].length,h:rows.length,ax:rows[0].length>>1,ay:rows.length>>1,halo:false,frames:{idle:[rows]}},o||{});   // Figur, Anker Mitte
const pxGen=(w,h,fn)=>{ const rows=[]; for(let y=0;y<h;y++){ let s=''; for(let x=0;x<w;x++) s+=fn(x,y)||'.'; rows.push(s); } return rows; };
const pxShift=(rows,dx)=>rows.map(r=>r.slice(dx)+r.slice(0,dx));
const pxBand=rows=>rows.concat(pxShift(rows,4),rows,pxShift(rows,4));   // 4-zeiliges Band → 16 Zeilen, jede zweite Lage um 4 versetzt
/* Risse für den Schadenszustand: Punkte [x,y] werden '0', sofern dort etwas ist */
const pxCrack=(rows,pts)=>rows.map((r,y)=>r.split('').map((c,x)=>c!=='.'&&pts.some(p=>p[0]===x&&p[1]===y)?'0':c).join(''));

